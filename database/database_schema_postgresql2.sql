-- =========================================================
-- โครงสร้างฐานข้อมูลหลังบ้าน (Database Schema) - PostgreSQL
-- ระบบช่วยเหลือและจัดการเรื่องร้องเรียนภายในสถาบัน (Issue Reporting & Community System)
