-- ---------------------------------------------------------
-- ลบ ENUM type เดิม (ถ้ามี) เผื่อรันซ้ำ
-- ---------------------------------------------------------
DROP TYPE IF EXISTS user_role CASCADE;
DROP TYPE IF EXISTS post_status CASCADE;
DROP TYPE IF EXISTS report_status CASCADE;

-- ENUM บทบาท: นักศึกษา / อาจารย์ / บุคลากร / แอดมิน
CREATE TYPE user_role AS ENUM ('Admin', 'นักศึกษา', 'อาจารย์', 'บุคลากร');

-- ENUM สถานะโพสต์: ใช้ 'สำเร็จแล้ว' และ 'ปิดงานแล้ว'
CREATE TYPE post_status AS ENUM ('เปิด', 'กำลังดำเนินการ', 'สำเร็จแล้ว', 'ปิดงานแล้ว');

-- ENUM สถานะการแจ้งปัญหาตัวระบบกับแอดมิน
CREATE TYPE report_status AS ENUM ('รอตรวจสอบ', 'กำลังแก้ไข', 'แก้ไขแล้ว');

-- ---------------------------------------------------------
-- 1. ตาราง Users (ข้อมูลผู้ใช้งาน)
-- ---------------------------------------------------------
DROP TABLE IF EXISTS Users CASCADE;
CREATE TABLE Users (
    User_ID     VARCHAR(10)     PRIMARY KEY,
    User_Name   VARCHAR(100)    NOT NULL,
    email       VARCHAR(150)    NOT NULL UNIQUE,
    password    VARCHAR(255)    NOT NULL,
    role        user_role       NOT NULL DEFAULT 'นักศึกษา',
    created_at  TIMESTAMP       DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------
-- 2. ตาราง Category (ข้อมูลหมวดหมู่หรือห้อง)
-- ---------------------------------------------------------
DROP TABLE IF EXISTS Category CASCADE;
CREATE TABLE Category (
    Category_ID     VARCHAR(10)     PRIMARY KEY,
    Category_name   VARCHAR(100)    NOT NULL,
    description     TEXT
);

-- ---------------------------------------------------------
-- 3. ตาราง Post (ข้อมูลโพสต์ / แจ้งปัญหา / มุมติว)
-- ---------------------------------------------------------
DROP TABLE IF EXISTS Post CASCADE;
CREATE TABLE Post (
    Post_ID         SERIAL          PRIMARY KEY,
    User_ID         VARCHAR(10)     NOT NULL,
    Category_ID     VARCHAR(10)     NOT NULL,
    title           VARCHAR(255)    NOT NULL,
    content         TEXT,
    image           VARCHAR(255),
    status          post_status     NOT NULL DEFAULT 'เปิด',
    created_at      TIMESTAMP       DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_post_user
        FOREIGN KEY (User_ID) REFERENCES Users(User_ID)
        ON UPDATE CASCADE ON DELETE CASCADE,

    CONSTRAINT fk_post_category
        FOREIGN KEY (Category_ID) REFERENCES Category(Category_ID)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- ---------------------------------------------------------
-- 4. ตาราง Comment (ข้อมูลความคิดเห็น)
-- ---------------------------------------------------------
DROP TABLE IF EXISTS Comment CASCADE;
CREATE TABLE Comment (
    Comment_ID      VARCHAR(10)     PRIMARY KEY,
    Post_ID         INT             NOT NULL,
    User_ID         VARCHAR(10)     NOT NULL,
    comment_text    TEXT            NOT NULL,
    created_at      TIMESTAMP       DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_comment_post
        FOREIGN KEY (Post_ID) REFERENCES Post(Post_ID)
        ON UPDATE CASCADE ON DELETE CASCADE,

    CONSTRAINT fk_comment_user
        FOREIGN KEY (User_ID) REFERENCES Users(User_ID)
        ON UPDATE CASCADE ON DELETE CASCADE
);

-- ---------------------------------------------------------
-- 5. ตาราง History (คลังประวัติโพสต์ที่ สำเร็จแล้ว / ปิดงานแล้ว)
-- ---------------------------------------------------------
DROP TABLE IF EXISTS History CASCADE;
CREATE TABLE History (
    History_ID   VARCHAR(10)     PRIMARY KEY,
    Post_ID      INT             NOT NULL,
    resolved_at  TIMESTAMP       DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_history_post
        FOREIGN KEY (Post_ID) REFERENCES Post(Post_ID)
        ON UPDATE CASCADE ON DELETE CASCADE
);

-- ---------------------------------------------------------
-- 6. ตาราง Report (ข้อมูลรายงานปัญหาระบบกับแอดมิน)
-- ---------------------------------------------------------
DROP TABLE IF EXISTS Report CASCADE;
CREATE TABLE Report (
    Report_ID       VARCHAR(10)     PRIMARY KEY,
    User_ID         VARCHAR(10)     NOT NULL,
    issue_title     VARCHAR(255)    NOT NULL,
    error_details   TEXT,
    screenshot      VARCHAR(255),
    created_at      TIMESTAMP       DEFAULT CURRENT_TIMESTAMP,
    admin_status    report_status   NOT NULL DEFAULT 'รอตรวจสอบ',

    CONSTRAINT fk_report_user
        FOREIGN KEY (User_ID) REFERENCES Users(User_ID)
        ON UPDATE CASCADE ON DELETE CASCADE
);

